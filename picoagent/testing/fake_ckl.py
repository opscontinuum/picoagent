def _escape(text: str) -> str:
    """Escape element text the way STIG Viewer (and ``ElementTree``) do, and only that way.

    Three characters are escaped in text content - ``&``, ``<``, ``>`` - and a carriage return
    becomes the numeric reference ``&#xD;`` so that XML line-ending normalisation cannot eat it.
    Quotes are *not* escaped in text; the reference export leaves them literal.
    """
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                .replace("\r", "&#xD;"))


def _element(depth: int, tag: str, text: str = "") -> str:
    """One tab-indented element on its own line, long form even when empty.

    The indent is built outside the f-string because a backslash inside an f-string expression
    is a syntax error before Python 3.12, and this package targets 3.11.
    """
    indent = "\t" * depth
    return f"{indent}<{tag}>{_escape(text)}</{tag}>\n"


def _renumber(pairs: list[tuple[str, str]], copy: int) -> list[tuple[str, str]]:
    """Give a repeated rule fresh identifiers so ``rules > 6`` still has unique lookup keys.

    Only used to build large checklists for the performance test; ``copy == 0`` is verbatim.
    """
    if copy == 0:
        return pairs
    offset = 1000 * copy
    renumbered = []
    for name, value in pairs:
        if name == "Vuln_Num":
            value = f"V-{int(value[2:]) + offset}"
        elif name == "Rule_ID":
            value = re.sub(r"SV-(\d+)", lambda m: f"SV-{int(m.group(1)) + offset}", value)
        elif name == "Rule_Ver":
            value = f"APSC-DV-{int(value.rsplit('-', 1)[1]) + offset:06d}"
        renumbered.append((name, value))
    return renumbered


