"""Fixture builders for the ``stig-runner`` plugin: a CKL checklist and a repository to probe.

Why the checklist is assembled by hand here rather than with ``xml.etree``
-------------------------------------------------------------------------
``ckl.py`` reads and writes CKL with ``xml.etree.ElementTree``. If this fixture used the same
library, the round-trip test would only prove ElementTree agrees with itself. So
:func:`build_ckl` emits the bytes with plain string formatting, copying the byte layout of a
real STIG Viewer 3.7.0 export: an XML declaration with double quotes, the
``<!--DISA STIG Viewer :: 3.7.0 -->`` comment, tab indentation, LF line endings, **no trailing
newline** after ``</CHECKLIST>``, empty elements in long form (``<HOST_NAME></HOST_NAME>``),
``&amp;``/``&lt;``/``&gt;`` for the three text-critical characters and ``&#xD;`` for a carriage
return inside element text. That last one is the trap the round trip has to survive: an XML
parser turns ``&#xD;`` into ``\r`` and a naive serialiser writes the raw byte back, silently
rewriting the file.

The rule content is real
------------------------
:data:`RULES` carries six rules copied verbatim from a checklist generated by STIG Viewer
3.7.0 for the Application Security and Development STIG V6R4 (``version 6``,
``Release: 4 Benchmark Date: 01 Oct 2025``), including their real ``Vuln_Num``, ``Rule_ID``,
``Rule_Ver``, CCI references and legacy ids. STIG content is a work of the US Government and
is not subject to copyright. The eight were chosen so the probe tests have something to find:
seven have entries in ``asd_probes.PROBES``, between them exercising all four probe kinds, and
one (APSC-DV-003236, the incident response plan) deliberately has none; APSC-DV-002490's check text contains ``<script>`` and ``<img …>``,
APSC-DV-002630's contains ``POA&Ms``, and APSC-DV-003236's fix text contains ``&#xD;`` - so
one fixture exercises each escaping rule above.

Note for anyone extending this: every one of the 286 rules in ASD V6R4 has
``Documentable`` = ``false``, so there is no "Documentable rule" to include.
"""
