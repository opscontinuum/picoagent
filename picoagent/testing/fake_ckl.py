def build_repo(tmp: Path) -> Path:
    """Write a synthetic repository for the evidence probes and return its root.

    Besides :data:`SAMPLE_FILES` it plants three things a probe must *skip*: a 2 MiB text file
    (over the size cap), a file whose first bytes contain NUL (binary), and - on POSIX only -
    a symlink pointing at the parent of the repository root, which is the shape of a path
    escape. Windows is skipped for the symlink because creating one there needs either
    developer mode or elevation, and a fixture must not require either.
    """
    root = tmp / "repo"
    for relative, content in SAMPLE_FILES.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")

    (root / "big.log").write_text("verify=False padding line\n" * 90_000, encoding="utf-8", newline="\n")
    (root / "app" / "blob.bin").write_bytes(b"\x00\x01verify=False\x00" + b"\xff" * 512)
    link = root / "escape"
    try:
        link.symlink_to(tmp.parent, target_is_directory=True)
    except (OSError, NotImplementedError):
        pass          # Windows without developer mode: the symlink test skips itself
    return root
