def result(ctx, text: str, is_error: bool = False, **details: Any) -> ToolResult:
    """Truncate to the session's limits and wrap. Same shape as es_doctor's helper, on purpose."""
    body, cut = truncate(text, ctx.config["tool_output_max_bytes"], ctx.config["tool_output_max_lines"])
    return ToolResult(ctx.tool_call_id, body + ("\n[truncated]" if cut else ""), is_error=is_error,
                      details=details)


class Session:
    """The one checklist a session is working on, and whether it has unsaved answers."""

    def __init__(self, interactive: bool = True):
        self.checklist: ckl.Checklist | None = None
        #: False only when the user set ``interactive = false`` in their config file.
        self.interactive = interactive

    def require(self) -> ckl.Checklist:
        if self.checklist is None:
            raise LookupError("no checklist loaded - run stig_load with the path to a .ckl file")
        return self.checklist


# --------------------------------------------------------------------------- rendering

def _asset_summary(asset: dict[str, str]) -> str:
    filled = [f"{name}={value}" for name, value in asset.items() if value]
    return ", ".join(filled) if filled else "(empty - fill it with stig_asset)"


def _counts_line(checklist: ckl.Checklist) -> str:
    tally = checklist.counts()
    total = len(checklist.rules)
    by_status = "  ".join(f"{status}: {tally.get(status, 0)}" for status in ckl.STATUSES)
    severities = []
    for severity in ("high", "medium", "low"):
        done = sum(tally.get(f"{severity} {status}", 0) for status in ckl.STATUSES
                   if status != "Not_Reviewed")
        in_severity = sum(tally.get(f"{severity} {status}", 0) for status in ckl.STATUSES)
        if in_severity:
            severities.append(f"{severity} {done}/{in_severity}")
    return f"{total} rules - {by_status}\nreviewed: {'  '.join(severities)}"


def _rule_line(rule: ckl.Rule) -> str:
    return f"{rule.vuln_num}  {rule.rule_ver}  {rule.severity:<6}  {rule.status:<14}  {rule.title}"


def _next_unreviewed(checklist: ckl.Checklist) -> ckl.Rule | None:
    """The rule a reviewer should look at next: highest severity first, document order within."""
    for severity in ("high", "medium", "low"):
        for rule in checklist.rules:
            if rule.severity == severity and rule.status == "Not_Reviewed":
                return rule
    return None


# --------------------------------------------------------------------------- tools

class _StigTool:
    """Base for the seven tools: holds the session and turns a missing checklist into an error."""

    def __init__(self, session: Session):
        self.session = session

    async def execute(self, args: dict, ctx) -> ToolResult:
        try:
            return await self.run(args, ctx)
        except LookupError as exc:
            return result(ctx, str(exc), is_error=True)
        except ckl.CklError as exc:
            return result(ctx, f"checklist error: {exc}", is_error=True)

    async def run(self, args: dict, ctx) -> ToolResult:      # pragma: no cover - overridden
        raise NotImplementedError


class LoadTool(_StigTool):
    name = "stig_load"
    description = ("Open a DISA STIG checklist (.ckl). Reports the STIG, its release, the asset "
                   "block and the rule counts by status and severity. Only one checklist is open "
                   "at a time; loading another replaces it.")
    parameters = {"type": "object", "properties": {
        "path": {"type": "string", "description": "path to the .ckl file"}}, "required": ["path"]}

    async def run(self, args: dict, ctx) -> ToolResult:
        try:
            path = resolve_path(ctx, args["path"])
        except PathRefused as exc:
            return result(ctx, str(exc), is_error=True)
        if not path.is_file():
            return result(ctx, f"no such file: {path}", is_error=True)
        try:
            checklist = ckl.load(path)
        except ckl.CklError as exc:
            return result(ctx, f"cannot load {path}: {exc}", is_error=True)

        self.session.checklist = checklist
        numbers = [rule.vuln_num for rule in checklist.rules]
        lines = [f"{checklist.title}", f"{checklist.release}", f"file: {path}",
                 f"asset: {_asset_summary(checklist.asset)}", _counts_line(checklist),
                 f"Vuln_Num range: {numbers[0]}..{numbers[-1]}" if numbers else "no rules"]
        return result(ctx, "\n".join(lines), path=str(path), rules=len(checklist.rules),
                      counts=checklist.counts())


class RulesTool(_StigTool):
    name = "stig_rules"
    description = ("List rules from the loaded checklist, one line each, filtered by status, "
                   "severity and/or a case-insensitive substring of the title, Rule_Ver or "
                   "Vuln_Num. Use this to pick what to review next.")
    parameters = {"type": "object", "properties": {
        "status": {"type": "string", "description": "Not_Reviewed | Open | NotAFinding | Not_Applicable"},
        "severity": {"type": "string", "description": "high | medium | low"},
        "query": {"type": "string", "description": "case-insensitive substring over title, Rule_Ver, Vuln_Num"},
        "offset": {"type": "integer"},
        "limit": {"type": "integer", "description": "default 40"}}}

    async def run(self, args: dict, ctx) -> ToolResult:
        checklist = self.session.require()
        status, severity = args.get("status"), args.get("severity")
        if status and status not in ckl.STATUSES:
            return result(ctx, f"unknown status {status!r}; expected one of {', '.join(ckl.STATUSES)}",
                          is_error=True)
        query = (args.get("query") or "").lower()
        matched = [rule for rule in checklist.rules
                   if (not status or rule.status == status)
                   and (not severity or rule.severity == severity)
                   and (not query or query in f"{rule.title} {rule.rule_ver} {rule.vuln_num}".lower())]

        offset = max(0, int(args.get("offset") or 0))
        limit = max(1, int(args.get("limit") or 40))
        page = matched[offset:offset + limit]
        if not page:
            return result(ctx, f"no rules match (of {len(checklist.rules)} in the checklist)")
        header = (f"{len(matched)} matching rules; showing {offset + 1}-{offset + len(page)}")
        return result(ctx, header + "\n" + "\n".join(_rule_line(rule) for rule in page),
                      matched=len(matched))


