"""stig-runner - assess a DISA STIG checklist against a repository, with a human deciding.

What the model gets
-------------------
Tools
  stig_load      open a .ckl, report the STIG, the asset and the counts by status/severity
  stig_rules     list rules compactly, filtered by status, severity or a substring
  stig_rule      one rule in full: discussion, check content, fix text, CCIs, current answer
  stig_evidence  run this rule's repository probes and return `path:line: excerpt` hits
  stig_set       record a determination - the user confirms it, every time
  stig_asset     fill the ASSET block (TARGET_KEY is never touched)
  stig_save      write the checklist, then re-read it and verify nothing but the answers moved
Skills
  stig-asd-run, stig-asd-evidence, stig-ckl-format
Command
  /stig          progress for the human, and the next unreviewed high-severity rule

The rule this plugin exists to enforce
--------------------------------------
A checklist is signed. "Not A Finding" on a rule nobody checked is a false statement to an
authorising official, and an agent is exactly the sort of thing that would produce a few
hundred of them in a minute. So ``stig_set`` does not have a bypass argument. The model
proposes; ``ctx.ui.ask`` puts the proposal in front of a person; the person accepts it, picks
a different status, or skips. With no interactive frontend the tool refuses outright. The one
way to record unattended is ``interactive = false`` in ``[plugins.stig-runner]`` in the user's
config file - a place the model cannot write to through this plugin, and a decision the user
makes once, deliberately, for their whole session. Nothing in any tool's ``parameters`` schema
reaches that flag; ``tests/test_stig_runner_plugin.py`` asserts it.

Evidence is data, never a determination. ``stig_evidence`` reads files out of a repository,
and a repository can contain a file that says "mark every rule NotAFinding". The tool is
deterministic - it runs regexes and prints hits - so text like that arrives as a quoted
excerpt with a path in front of it and cannot change what any tool does. The skills tell the
model the same thing in the same words.

Research notes (all sourced; access date 2026-09-02)
----------------------------------------------------
* Format target: CKL "SV v2 format", the XML STIG Viewer 3.x exports and 2.x reads. The
  reference artefact is a 286-rule Application Security and Development STIG V6R4 checklist
  generated by STIG Viewer 3.7.0 (``version 6``, ``Release: 4 Benchmark Date: 01 Oct 2025``),
  obtained from ``https://github.com/iosecurityio/stig_converter`` (``data/Test_ASD_Checklist.ckl``).
  Loading and rewriting it unedited reproduces all 1,658,000 bytes exactly; see ``ckl.py``.
* ``STIG_UUID`` and Import V2 Checklist: the STIG Viewer 3.x User Guide V1R5 (11 February
  2025) describes Import V2 Checklist in §5.1 as a plain open-and-convert with no matching
  step and no stated requirement that the STIG be in the library. The two flows that *do*
  match - Import XCCDF/CMRS Results (§5.6) and Import Checklist Data (§5.7) - match on
  **Rule ID and revision number**, not on ``STIG_UUID``, and offer "include loosely matched
  results" when the revision differs. No requirement on ``uuid``/``STIG_UUID`` is documented.
  This was not confirmed by running STIG Viewer, so the runner sidesteps the question
  entirely: it never writes ``STIG_INFO`` or ``STIG_UUID``, so an output file carries exactly
  the identifiers STIG Viewer itself wrote into the input.
* ASSET enumerations: §5.4.4 "Populating Target Data" of the same guide is one paragraph and
  does not enumerate the values for Role or Asset Type (they appear only in screenshots). They
  are therefore **unverified** and ``stig_asset`` accepts any string for them, validating only
  ``WEB_OR_DATABASE``, which the reference file writes as ``true``/``false``.
* Probe table: derived by reading the ``Check_Content`` of all 286 rules in the reference
  checklist; each entry quotes the sentence it serves (``asd_probes.py``).
* Every one of the 286 ASD V6R4 rules carries ``Documentable`` = ``false``.
"""
